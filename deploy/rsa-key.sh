#!/bin/sh
# The login RSA key (ot-server#17). The repository's key.pem is the public
# OpenTibia key: anyone can decrypt logins made with it. Production uses its
# own key, kept out of git:
#
#   deploy/rsa-key.sh            create deploy/secrets/rsa-key.pem (once)
#   deploy/rsa-key.sh public     print the public modulus (for the client)
#
# The server reads the key from /run/secrets/rsa_key (docker-compose.yml);
# the web client gets the public half from secrets/rsa-public.js (written
# here, served as /play/rsa-public.js). To rotate the key: move both files
# away, run this again and restart the stack (server and web together);
# players reload the page.
set -eu
cd "$(dirname "$0")"
KEY=secrets/rsa-key.pem

if [ "${1:-}" = "public" ]; then
	openssl rsa -in "$KEY" -noout -modulus | cut -d= -f2 | python3 -c 'import sys; print(int(sys.stdin.read().strip(), 16))'
	exit 0
fi

if [ -e "$KEY" ]; then
	echo "$KEY already exists; move it (and secrets/rsa-public.js) away first to make a new one." >&2
	exit 1
fi
mkdir -p secrets
chmod 700 secrets
# The 7.x login packet holds exactly one 128-byte block: a 1024-bit key
openssl genrsa -traditional -out "$KEY" 1024 2>/dev/null || openssl genrsa -out "$KEY" 1024
# Readable by the game server only: it runs as uid 1000 in its container, and
# Compose mounts the file with its host owner and mode (secrets' uid/mode
# settings only apply under Swarm). The secrets folder is 700, so nobody else
# on the host gets to it.
chown 1000:1000 "$KEY" 2>/dev/null || echo "Note: could not give $KEY to uid 1000 (run as root); the server must be able to read it." >&2
chmod 600 "$KEY"
# The public half for the web client (no secret in it)
MODULUS=$(openssl rsa -in "$KEY" -noout -modulus | cut -d= -f2 | python3 -c 'import sys; print(int(sys.stdin.read().strip(), 16))')
printf '// Generated by deploy/rsa-key.sh: the public half of the login key\nwindow.otclientConfig = window.otclientConfig || {};\nwindow.otclientConfig.rsaPublicKey = "%s";\n' "$MODULUS" > secrets/rsa-public.js
# The public half: nothing secret in it, the web container serves it
chmod 644 secrets/rsa-public.js
echo "Created $KEY. Keep a copy in a safe place (losing it means a new key and a page reload for everyone)."
